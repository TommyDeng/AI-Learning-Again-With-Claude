import pandas as pd

df = pd.DataFrame(
    {
        "城市": ["台北", "高雄", "台中", "台北", "高雄"],
        "等级": ["高", "中", "低", "中", "高"],
    }
)

# One-Hot编码:适合"没有顺序关系"的类别(如城市)
df_onehot = pd.get_dummies(df, columns=["城市"])
print(df_onehot)


# Label编码:适合"有顺序关系"的类别(如等级:低<中<高)
order = {"低": 0, "中": 1, "高": 2}
df["等级_编码"] = df["等级"].map(order)
print(df)


# 常见误区: 不要对"城市"这种无序类别直接用数字编码(台北=0, 高雄=1, 台中=2)——这会让模型误以为"高雄比台北大、台中比高雄更大"，产生根本不存在的顺序关系。
# 无序类别一定用One-Hot。
