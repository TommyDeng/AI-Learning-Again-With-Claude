import pandas as pd

df = pd.DataFrame(
    {
        "出生年份": [1990, 1985, 2000, 1995],
        "身高_cm": [170, 165, 180, 175],
        "体重_kg": [65, 55, 80, 70],
    }
)

current_year = 2026
df["年龄"] = current_year - df["出生年份"]  # 从原始数据派生新特征
df["BMI"] = df["体重_kg"] / (df["身高_cm"] / 100) ** 2  # 组合多个特征

print(df)


# 特征工程的核心思想: 很多时候，原始数据里不存在的"组合特征"反而更有预测力(比如BMI比单独的身高体重更能反映健康状况)。好的特征工程往往比换一个更复杂的模型效果更明显——这也是为什么它被称为"机器学习里最有性价比的一步"。
