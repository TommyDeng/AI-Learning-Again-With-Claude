from llm import ask

text = "公司本季度营收增长12%,但净利润下降8%,主要因为研发投入大幅增加,同时海外市场拓展带来了一次性成本。"

# 模糊的提示词
print(ask(f"总结一下:{text}"))
print("-" * 40)

# 具体的提示词:说明受众、长度、格式、重点
prompt = f"""你是一名财经编辑。请为忙碌的高管总结下面这段财报摘要。

要求:
- 不超过两句话
- 先说结论,再说原因
- 不要使用"值得注意的是"这类套话

财报摘要:{text}"""
print(ask(prompt))

# 核心原则: 把模型当成一个聪明但对你的情况一无所知的新同事。
# 你没说的背景,它不会知道。好的提示词通常说清四件事:角色/受众、任务、约束、输出格式。
