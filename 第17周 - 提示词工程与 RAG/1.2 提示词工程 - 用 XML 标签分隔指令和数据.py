from llm import ask

review = "房间很干净,但是隔音太差了,半夜一直听到隔壁电视声。前台态度不错。"

prompt = f"""分析下面的酒店评论,提取优点和缺点。

<review>
{review}
</review>

按以下格式输出:
<pros>优点,用分号分隔</pros>
<cons>缺点,用分号分隔</cons>"""

print(ask(prompt))


# 标签的作用:

# 让模型清楚哪部分是指令、哪部分是待处理的数据
# 输出也用标签,你可以用正则轻松解析
# 如果数据里恰好有"忽略上面的指令"这类文字,标签能降低被它干扰的风险(这叫提示词注入,做 RAG 时尤其要注意,后面会再提到)
